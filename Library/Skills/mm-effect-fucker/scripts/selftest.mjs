import fs from 'node:fs/promises';
import path from 'node:path';
import assert from 'node:assert/strict';
import {parseArgs} from 'node:util';
import {withBrowser} from './browser.mjs';
import {capture} from './media.mjs';
import {Root,readJson,writeJson,newDirectory,hash,run,executable} from './io.mjs';

const {values:Options}=parseArgs({options:{out:{type:'string'},browser:{type:'string'},ffmpeg:{type:'string'},ffprobe:{type:'string'}}});
if(!Options.out)throw new Error('Supply --out with a new evidence directory');
const Directory=await newDirectory(Options.out);
const CheckList=[];
const record=(Name)=>{CheckList.push(Name);process.stderr.write(`checked ${Name}\n`);};
try {
  const Manifest=await readJson(path.join(Root,'runtime/manifest.json'));
  for(const Entry of Manifest.sources)assert.equal(hash(await fs.readFile(path.join(Root,'assets/forge-core',Entry.path))),Entry.sha256,Entry.path);
  record('vendored source hashes');
  const Sample=await readJson(path.join(Root,'assets/examples/sumi-forward.fxpreset.json'));
  const SampleHash=hash(JSON.stringify(Sample));
  await withBrowser(Options,async Api=>{
    const Trail=(await Api.call('textureStats')).trail;
    assert.ok(Trail.head<50&&Trail.edge<50&&Trail.middle>230&&Trail.tail>230,JSON.stringify(Trail));record('trail keeps its middle and tail alpha while softening its head and sides');
    const Birth=await Api.call('defaults','3d','Birth velocity regression');
    const BirthSchema=await Api.call('schema');
    Birth.effect.background='#000000';Birth.effect.duration=1;Birth.effect.bloom.enabled=false;Birth.effect.showCharacter=false;
    Birth.effect.layers=[{...BirthSchema.emitter3d,id:'birthvelocity',rate:0,bursts:[{time:0,count:1}],position:{x:0,y:0,z:0},rotation:{x:0,y:0,z:0},radius:0,startSpeed:{min:0,max:0},startLifetime:{min:1,max:1},startSize:{min:.4,max:.4},startRotation:{min:0,max:0},velocity:{x:4,y:0,z:0},colors:[{t:0,color:'#ffffff'},{t:1,color:'#ffffff'}],fadeIn:0,fadeOut:0,sizeEnd:1,renderMode:'stretched',lengthScale:6,velocityScale:0}];
    const BirthLoaded=await Api.call('load',Birth);
    await Api.call('configure',{width:320,height:180,view:{position:[0,0,10],target:[0,0,0],fov:40}});
    const BirthImage=await Api.call('frame',BirthLoaded.index,0);
    const BirthPng=path.join(Directory,'birth-stretched.png');
    await fs.writeFile(BirthPng,Buffer.from(BirthImage.split(',')[1],'base64'),{flag:'wx'});
    const BirthRaw=path.join(Api.temp,'birth-stretched.rgba');
    await run(await executable(Options.ffmpeg,'ffmpeg'),['-v','error','-i',BirthPng,'-f','rawvideo','-pix_fmt','rgba',BirthRaw]);
    const Pixels=await fs.readFile(BirthRaw);let MinX=320,MinY=180,MaxX=-1,MaxY=-1;
    for(let Y=0;Y<180;Y++)for(let X=0;X<320;X++)if(Pixels[(Y*320+X)*4]>32){MinX=Math.min(MinX,X);MaxX=Math.max(MaxX,X);MinY=Math.min(MinY,Y);MaxY=Math.max(MaxY,Y);}
    const BirthBounds={width:MaxX-MinX+1,height:MaxY-MinY+1};
    await writeJson(path.join(Directory,'birth-stretched.json'),BirthBounds);
    assert.ok(BirthBounds.height>0&&BirthBounds.width>BirthBounds.height*3,JSON.stringify(BirthBounds));record('stretched billboard faces configured velocity on its birth frame');
    const CurvedBirth = structuredClone(Birth);
    CurvedBirth.effect.layers[0].velocity.x = 0;
    CurvedBirth.effect.layers[0].velocityCurveX = [{t:0,v:4},{t:1,v:0}];
    const CurvedLoaded = await Api.call('load', CurvedBirth);
    assert.equal(await Api.call('frame', CurvedLoaded.index, 0), BirthImage);
    record('stretched billboard uses the birth key of velocity curves');

    const MeshPreset = structuredClone(Birth);
    MeshPreset.effect.layers[0].renderMode = 'mesh';
    MeshPreset.effect.layers[0].mesh = 'm_testmesh';
    await assert.rejects(() => Api.call('load', MeshPreset), /Missing mesh m_testmesh/);
    MeshPreset.meshes = [{
      id:'m_testmesh', name:'Test mesh', description:'', createdAt:1, updatedAt:1,
      source:{type:'raw', positions:[-2,-1,0,2,-1,0,0,2,0], indices:[0,1,2]},
    }];
    const MeshLoaded = await Api.call('load', MeshPreset);
    const MeshFrame = await Api.call('frame', MeshLoaded.index, 0);
    const Variant = structuredClone(MeshPreset);
    Variant.meshes[0].source.positions[1] = 1;
    const VariantLoaded = await Api.call('load', {...Variant.effect, meshes:Variant.meshes});
    assert.notEqual(await Api.call('frame', VariantLoaded.index, 0), MeshFrame);
    assert.equal(await Api.call('frame', MeshLoaded.index, 0), MeshFrame);
    const MeshPackage = await Api.call('unity', MeshLoaded.index);
    const VariantPackage = await Api.call('unity', VariantLoaded.index);
    assert.notEqual(VariantPackage.scope, MeshPackage.scope);
    const MeshFile = MeshPackage.scope + '/Meshes/fx_mesh_m_testmesh.json';
    const MeshGeometry = JSON.parse(Buffer.from(MeshPackage.files[MeshFile], 'base64'));
    assert.deepEqual(MeshGeometry.positions, MeshPreset.meshes[0].source.positions);
    record('embedded meshes validate render and export with isolated variants');

    const Loaded=await Api.call('load',Sample);
    assert.equal(Loaded.bundle.effect.layers.length,19);assert.equal(Loaded.shaderCount,7);record('all seven sample shaders compile in WebGL');
    await Api.call('configure',{width:960,height:540,view:await readJson(path.join(Root,'assets/examples/sumi-view.json'))});
    const Frame=await Api.call('frame',Loaded.index,2.76);
    assert.ok(Frame.length>20000);record('ink sample renders visible detail');
    await Api.call('frame',Loaded.index,0.68);
    assert.equal(await Api.call('frame',Loaded.index,2.76),Frame);record('deterministic seek without frame-order dependence');
    assert.equal(await Api.call('frame',Loaded.index,0),await Api.call('frame',Loaded.index,4.6));record('one-shot empty loop boundary');
    const expectFailure=async (Value,Pattern,Name)=>{await assert.rejects(()=>Api.call('load',Value),Pattern);record(Name);};
    const Missing=structuredClone(Sample);Missing.shaders=[];
    await expectFailure(Missing,/Missing shader/,'missing shader rejected without material fallback');
    const MissingTrail = structuredClone(Sample);
    MissingTrail.effect.layers[0].trailTexture = 'a_missing';
    await expectFailure(MissingTrail, /Missing asset a_missing/, 'missing trail texture rejected');
    const MissingDissolve = structuredClone(Sample);
    MissingDissolve.effect.layers[0].material.dissolveTexture = 'a_missing';
    await expectFailure(MissingDissolve, /Missing asset a_missing/, 'missing dissolve texture rejected');
    const OverLimit=structuredClone(Sample);OverLimit.effect.layers=Array.from({length:33},(_,I)=>({...Sample.effect.layers[0],id:'layer'+I}));
    await expectFailure(OverLimit,/Sanitizer would change/,'layer truncation rejected');
    const Invalid=structuredClone(Sample);Invalid.effect.layers[0].alpha=-2;
    await expectFailure(Invalid,/Sanitizer would change/,'silent value clamps rejected');
    const Shader=structuredClone(Sample);Shader.shaders[0].code='vec4 fxCustom(vec2 uv, vec4 tint, float life, float rnd, float age) { return vec4(undefinedValue); }';
    await expectFailure(Shader,/undefinedValue|undeclared/,'shader compile failure surfaced');
    const Flat=await Api.call('defaults','2d','2D Smoke Test');
    const FlatLoaded=await Api.call('load',Flat);
    assert.ok((await Api.call('frame',FlatLoaded.index,.5)).length>1000);record('2D preview renderer');
    await assert.rejects(()=>Api.call('unity',FlatLoaded.index),/requires a 3D/);record('2D cannot masquerade as ParticleSystem export');
    const Asset=await Api.call('generate','arc',{},'Generated arc','a_testarc');
    assert.ok(Asset.dataUrl.startsWith('data:image/png;base64,'));assert.ok(Asset.width>0);record('procedural texture generation');
    const Textured=structuredClone(Sample);Textured.assets.push(Asset);Textured.effect.layers[0].material.texture=Asset.id;
    const TextureLoaded=await Api.call('load',Textured);
    const Unity=await Api.call('unity',TextureLoaded.index);
    assert.equal(Buffer.from(Unity.zip,'base64').subarray(0,2).toString(),'PK');
    assert.ok(Object.keys(Unity.files).some(Name=>Name.includes('a_testarc.png')));
    assert.equal(Object.keys(Unity.files).filter(Name=>Name.includes('FxForgeCustom_')).length,7);
    const EffectName=Object.keys(Unity.files).find(Name=>Name.includes('/Effects/')&&Name.endsWith('.fxforge.json'));
    assert.equal(JSON.parse(Buffer.from(Unity.files[EffectName],'base64')).layers.length,19);record('Unity export contains 19 layers seven shaders and embedded texture');
    const OriginalUnity=await Api.call('unity',Loaded.index);
    assert.notEqual(OriginalUnity.scope,Unity.scope);
    assert.ok(Object.keys(OriginalUnity.files).filter(Name=>/\/(Textures|Meshes|Effects)\//.test(Name)).every(Name=>Name.startsWith(OriginalUnity.scope+'/')));
    assert.ok(OriginalUnity.files[OriginalUnity.scope+'/README.txt']);
    assert.ok(!OriginalUnity.files['FXForge/README.txt']);
    record('different effect contents isolate generated materials meshes and textures');
    const RenderDirectory=await newDirectory(path.join(Directory,'render'));
    const Report=await capture(Api,{...Options,'view-file':path.join(Root,'assets/examples/sumi-view.json'),mp4:true,times:'0.64,0.72,0.80,0.88,2.76,2.84,2.92,3.00'},RenderDirectory,Loaded);
    assert.equal(Report.frameCount,115);record('full 115-frame GIF and MP4 capture');
    const CompareDirectory=await newDirectory(path.join(Directory,'compare'));
    const Comparison=await capture(Api,{...Options,start:'0.48',end:'1.12',speed:'0.5',width:'480',height:'270'},CompareDirectory,Loaded,TextureLoaded);
    assert.equal(Comparison.frameCount,16);record('same-camera half-speed comparison');
    assert.equal(hash(JSON.stringify(Sample)),SampleHash);record('input bundle unchanged');
    assert.ok(Api.requests.every(Url=>Url.startsWith('http://127.0.0.1:')||Url.startsWith('data:')));record('renderer made no external requests');
  });
  const Probe=await executable(Options.ffprobe,'ffprobe');
  const Result=await run(Probe,['-v','error','-select_streams','v:0','-show_entries','stream=width,height,nb_frames,duration','-of','json',path.join(Directory,'render/preview.gif')]);
  const Stream=JSON.parse(Result.stdout).streams[0];
  assert.equal(Stream.width,960);assert.equal(Stream.height,540);assert.equal(Number(Stream.nb_frames),115);assert.equal(Number(Stream.duration),4.6);record('encoded GIF dimensions frames and duration');
  const Decode=await executable(Options.ffmpeg,'ffmpeg');
  await run(Decode,['-v','error','-i',path.join(Directory,'render/preview.gif'),'-f','null','-']);record('GIF fully decodes');
  const Evidence={ok:true,at:new Date().toISOString(),platform:process.platform,node:process.version,runtimeSha256:Manifest.browser.sha256,checks:CheckList,externalNetworkRequests:0,unityWrites:0,unityValidation:'not_run_by_this_selftest'};
  await writeJson(path.join(Directory,'selftest.json'),Evidence);
  console.log(JSON.stringify(Evidence,null,2));
} catch(Error) {
  await writeJson(path.join(Directory,'failure.json'),{ok:false,completedChecks:CheckList,error:Error.stack??String(Error)});
  console.error(Error);process.exitCode=1;
}
